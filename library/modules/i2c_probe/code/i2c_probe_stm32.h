#ifndef I2C_PROBE_STM32_H
#define I2C_PROBE_STM32_H

#include <stdint.h>

/* I2C 总线原语（stm32，ADR 0009 口径的纯驱动切片）：借一对脚 + 一条总线，只做
 * 「问在不在」与「读一个寄存器」两件事。
 *
 * **本件不是器件驱动**：它不认识 WHO_AM_I，不知道任何器件语义，也**不写寄存器、
 * 不读数据**——猜出来的读法比不测更坏。它的用途是给「手上这件器件不在模块库里」
 * 的场景提供一段确定性的通信探测。
 *
 * 实现 = **位操作软 I2C 自实现**（照 aht10 / sht20 / qmc5883l 先例：SDA 方向
 * 运行时切换、SCL 显式初始化、半周期 5us ≈ 100kHz 级），**不用母版 ml_i2c**——
 * 其 I2C_GPIO 硬绑 PA11/PA12，那两个脚在蓝药丸上是 USB DM/DP（库内软 I2C 件
 * 明确不用它的既有决策）。引脚 = 母版 pin_config.h 单源
 * I2C_PROBE_SCL_GPIO / _SCL_PIN / _SDA_GPIO / _SDA_PIN，默认 PA6（SCL）/
 * PA7（SDA）——与库内软 I2C 件**共挂同一条总线**（器件地址各异、多挂协议允许
 * = 合法共享）。总线需板上或模块自带上拉电阻（开漏 + 上拉）。
 *
 * 接口与 mspm0 版（i2c_probe.h）**同名同语义同返回码**：0 = 成功/有应答，
 * 1 = 失败/无应答。调用方按这两份头文件写代码，两平台零交叉改动。
 * ⚠ **两平台 ping 的线上字节刻意对齐**：都是「START + 器件地址 + **读位** +
 * 读 1 字节（丢弃）」，问的是同一件事——「这个地址的**读方向**有没有东西
 * 应答」。只应答写地址的从机（罕见）在两平台都会判无应答：**宁可两边一致，
 * 不要一边说通一边说不通**。要更进一步的确认，用 i2c_probe_read_reg 走一整条
 * 读写事务。两个 ping 都**不发任何写数据字节**、都看不出器件型号。
 *
 * 未上板：编译矩阵只证「能编译」，不证器件真能应答。 */

/* i2c_probe_init：按需初始化总线。
 *
 * SCL / SDA 都显式配成开漏输出并置高（总线空闲电平）——F1 复位后 GPIO 是浮空
 * 输入、写 ODR 不生效，不显式初始化就是一条死总线（库内六件软 I2C 的批次 3
 * 回修先例）。重复调用无害。 */
void i2c_probe_init(void);

/* i2c_probe_ping：问「7 位地址 addr7 上有没有器件应答」。
 *
 * 返回 0 = 有应答、1 = 无应答。地址非法（> 0x7F）= 1。
 * 实现 = START + **读地址** + 读 1 字节（丢弃）+ 非应答 + 停止——与 mspm0 侧
 * 同一个问法（线上字节刻意对齐）。**不发任何写数据字节**。 */
uint8_t i2c_probe_ping(uint8_t addr7);

/* i2c_probe_read_reg：读器件 7 位地址 addr7 上、8 位寄存器地址 reg 的值。
 *
 * 返回 0 = 成功（读回值经出参 *value 带回）、1 = 失败。**读回值与返回码两分**：
 * 失败时 *value 不被写、也不会与「读到的 0x00」混淆——这正是本件要解决的问题。
 * 地址非法（> 0x7F）或 value 为空指针 = 1。
 *
 * 实现 = 写寄存器指针 → **重复起始** → 读地址 → 读 1 字节 → 非应答 → 停止：
 * 中途不发停止条件（停止会让一部分器件复位寄存器指针、读回错值）。 */
uint8_t i2c_probe_read_reg(uint8_t addr7, uint8_t reg, uint8_t *value);

#endif /* I2C_PROBE_STM32_H */
