#ifndef I2C_PROBE_H
#define I2C_PROBE_H

#include <stdint.h>

/* I2C 总线原语（mspm0，ADR 0009 口径的纯驱动切片）：借一对脚 + 一条总线，只做
 * 「问在不在」与「读一个寄存器」两件事。
 *
 * **本件不是器件驱动**：它不认识 WHO_AM_I，不知道任何器件语义，也**不写寄存器、
 * 不读数据**——猜出来的读法比不测更坏。它的用途是给「手上这件器件不在模块库里」
 * 的场景提供一段确定性的通信探测，并让这段探测代码进得了生成门禁（mspm0 上
 * main.c 只准调「所选模块头里真实存在的函数」）。
 *
 * 总线 = 母版 SysConfig 的**硬件 I2C 实例 I2C_0**（`I2C_0_INST`），默认
 * SDA=PA0 / SCL=PA1——与板载 LED 共用那两个脚，通信期间 LED 微闪属正常现象；
 * PA0 的板载上拉位未焊，依赖模块板自带的上拉电阻。改脚改 mspm0.syscfg 的
 * I2C_0 实例，不改本模块。
 *
 * 接口与 stm32 版（i2c_probe_stm32.h）**同名同语义同返回码**：0 = 成功/有应答，
 * 1 = 失败/无应答。调用方按这两份头文件写代码，两平台零交叉改动。
 * ⚠ **两平台 ping 的线上字节刻意对齐**：都是「START + 器件地址 + **读位** +
 * 读 1 字节（丢弃）」，问的是同一件事——「这个地址的**读方向**有没有东西
 * 应答」。只应答写地址的从机（罕见）在两平台都会判无应答：**宁可两边一致，
 * 不要一边说通一边说不通**。要更进一步的确认，用 i2c_probe_read_reg 走一整条
 * 读写事务。两个 ping 都**不发任何写数据字节**、都看不出器件型号。
 *
 * 未上板：本平台硬件 I2C 路径的真机验证留后续（编译矩阵只证「能编译」）。 */

/* i2c_probe_init：按需初始化总线。
 *
 * mspm0 上是**空实现占位**——总线由 SYSCFG_DL_init() 按母版 mspm0.syscfg 的
 * I2C_0 实例配置好（joystick / ttp224 空实现先例）。留这个函数是给调用方一个
 * 「用总线之前先初始化一次」的位置，并让两平台 API 对齐。 */
void i2c_probe_init(void);

/* i2c_probe_ping：问「7 位地址 addr7 上有没有器件应答」。
 *
 * 返回 0 = 有应答、1 = 无应答（或总线忙等超时）。地址非法（> 0x7F）= 1。
 * 实现 = START + 器件地址 + **读位** + 读 1 字节（丢弃）——与 stm32 侧同一个
 * 问法（线上字节刻意对齐）。**不发任何写数据字节**；读回的那一字节不参与
 * 判定、也不出参。 */
uint8_t i2c_probe_ping(uint8_t addr7);

/* i2c_probe_read_reg：读器件 7 位地址 addr7 上、8 位寄存器地址 reg 的值。
 *
 * 返回 0 = 成功（读回值经出参 *value 带回）、1 = 失败。**读回值与返回码两分**：
 * 失败时 *value 不被写、也不会与「读到的 0x00」混淆——这正是本件要解决的问题。
 * 地址非法（> 0x7F）或 value 为空指针 = 1。
 *
 * 实现 = 写寄存器指针 → **重复起始** → 读地址 → 读 1 字节 → 停止：中途不发
 * 停止条件（停止会让一部分器件复位寄存器指针、读回错值）。 */
uint8_t i2c_probe_read_reg(uint8_t addr7, uint8_t reg, uint8_t *value);

#endif /* I2C_PROBE_H */
